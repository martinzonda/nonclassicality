import numpy as np
from scipy.optimize import linprog, minimize_scalar, OptimizeResult
from numpy.polynomial.polynomial import polyroots, polyval, polytrim


def pvec_mu(mu, indx, fact):
    """
    Return the vector p(mu) restricted to the selected indices indx:
        p_k(mu) = exp(-mu) * mu^k / k!
    assuming fact[k] = 1 / k!.
    """
    indx = np.asarray(indx, dtype=int).reshape(-1)
    fact = np.asarray(fact, dtype=float).reshape(-1)
    mu = float(mu)

    return np.exp(-mu) * (mu ** indx) * fact[indx]

def is_redundant_cut(mu_star, mu_list, indx, fact, row_tol=1e-12):
    """
    Return True if the cut generated by mu_star is numerically redundant
    with an existing cut in mu_list, based on the Poisson row vector.
    """
    p_new = pvec_mu(mu_star, indx, fact)

    # Numerically zero cut is already covered by t >= 0
    if np.max(np.abs(p_new)) < 1e-14:
        return True

    for mu_old in mu_list:
        p_old = pvec_mu(mu_old, indx, fact)

        # Compare actual row vectors, not just mu values
        if np.max(np.abs(p_new - p_old)) <= row_tol * max(1.0, np.max(np.abs(p_new))):
            return True

    return False

def prune_duplicate_rows(A_ub, b_ub, row_tol=1e-12):
    """
    Remove rows of A_ub that are numerically redundant with earlier rows.
    Since all b_ub entries are 0 here, it is enough to compare A_ub rows.
    """
    A_ub = np.asarray(A_ub, dtype=float)
    b_ub = np.asarray(b_ub, dtype=float)

    keep_rows = []
    keep_rhs = []

    for i in range(A_ub.shape[0]):
        row = A_ub[i]

        is_duplicate = False
        for kept in keep_rows:
            if np.max(np.abs(row - kept)) <= row_tol * max(1.0, np.max(np.abs(row))):
                is_duplicate = True
                break

        if not is_duplicate:
            keep_rows.append(row)
            keep_rhs.append(b_ub[i])

    return np.array(keep_rows, dtype=float), np.array(keep_rhs, dtype=float)

def solve_master_lp(probs, indx, fact, bounds, mu_list,lp_failed_continue=False):
    """
    Solve the finite master LP

        minimize    t - lam · probs
        subject to  t >= lam · p(mu_m)   for all mu_m in mu_list
                    t >= 0
                    bounds on lam

    where lam has one component per selected index in indx.
    """
    probs = np.asarray(probs, dtype=float).reshape(-1)
    indx = np.asarray(indx, dtype=int).reshape(-1)
    fact = np.asarray(fact, dtype=float).reshape(-1)

    n = len(probs)
    if len(indx) != n:
        raise ValueError(f"len(probs)={n} but len(indx)={len(indx)}")
    if len(bounds) != n:
        raise ValueError(f"len(bounds)={len(bounds)} but n={n}")

    c = np.zeros(n + 1)
    c[:n] = -probs
    c[n] = 1.0

    A_ub = []
    b_ub = []

    # Constraints: lam · p(mu_m) - t <= 0

    for mu in mu_list:
        p = pvec_mu(mu, indx, fact)
        # Skip cuts that are numerically indistinguishable from t >= 0
        pmax = np.max(np.abs(p))
        if pmax < 1e-14:
            continue
            
        scale = max(1.0, pmax)

        row = np.zeros(n + 1)
        row[:n] = p / scale
        row[n] = -1.0 / scale
        A_ub.append(row)
        b_ub.append(0.0)
        

    # Constraint: t >= 0  <=>  -t <= 0
    row = np.zeros(n + 1)
    row[n] = -1.0
    A_ub.append(row)
    b_ub.append(0.0)

    A_ub = np.array(A_ub, dtype=float)
    b_ub = np.array(b_ub, dtype=float)

    #A_ub, b_ub = prune_duplicate_rows(A_ub, b_ub, row_tol=1e-12)  # This should increase stability for systems with N_P>12
    
    lp_bounds = list(bounds) + [(None, None)]

    #res = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=lp_bounds, method="highs")
    
    # First try dual simplex
    res = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=lp_bounds, method="highs-ds")

    # Fallback to IPM
    if not res.success:
        res = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=lp_bounds, method="highs-ipm")

    # If still failed, either stop or return a safe fallback solution
    if not res.success:
        if not lp_failed_continue:
            raise RuntimeError(f"linprog failed: {res.message}")

        lam = np.zeros(n, dtype=float)
        t = 0.0

        fallback_res = OptimizeResult({
            "x": np.concatenate([lam, [t]]),
            "success": False,
            "status": -999,
            "message": f"LP failed; returned fallback solution lam=0, t=0. Original solver message: {res.message}",
            "fun": 0.0,
            "nit": 0,
            "lp_failed_fallback": True,
        })

        return lam, t, fallback_res


    lam = res.x[:n]
    t = res.x[n]
    return lam, t, res


def max_inner_value(indx, lam, fact, imtol=1e-9):
    """
    Compute the *unclipped* supremum

        max_{mu >= 0} lam · p(mu)

    using the stationary-point equation.

    Returns
    -------
    worst_val : float
        The true supremum value, which may be negative.
    mu_star : float
        A finite candidate point giving the best sampled value among
        the stationary points and the boundary mu = 0.

    Notes
    -----
    If all finite candidates are negative, then the true supremum over mu >= 0
    is actually 0, attained only in the limit mu -> infinity, because
        lam · p(mu) -> 0.
    Therefore this routine explicitly compares the best finite value with 0.
    In that case it returns worst_val = 0.0, but mu_star is kept as the best
    finite candidate only for diagnostic purposes. The outer LP already handles
    the infinity branch through the separate constraint t >= 0.
    """
    indx = np.asarray(indx, dtype=int).reshape(-1)
    lam = np.asarray(lam, dtype=float).reshape(-1)
    fact = np.asarray(fact, dtype=float).reshape(-1)

    if indx.size == 0:
        return 0.0, 0.0

    if len(indx) != len(lam):
        raise ValueError(f"len(indx)={len(indx)} but len(lam)={len(lam)}")

    mxin = indx.max()

    # Dense lambda_k for k = 0, ..., mxin+1
    lam_aux = np.zeros(mxin + 2, dtype=float)
    lam_aux[indx] = lam

    # Stationary-point polynomial:
    #   sum_k (lambda_{k+1} - lambda_k) mu^k / k! = 0
    dcoef = (lam_aux[1:mxin+2] - lam_aux[:mxin+1]) * fact[:mxin+1]
    dcoef = polytrim(dcoef)

    if dcoef.size <= 1:
        candidates = np.array([0.0])
    else:
        roots = polyroots(dcoef)
        mask = (np.abs(roots.imag) < imtol) & (roots.real > 0.0)
        candidates = np.concatenate(([0.0], roots.real[mask]))

    coef = lam_aux[:mxin+1] * fact[:mxin+1]
    vals = polyval(candidates, coef) * np.exp(-candidates)

    imax = np.argmax(vals)
    mu_star = float(candidates[imax])
    val = float(vals[imax])

    # Include the limiting value 0 from mu -> infinity.
    worst_val = max(val, 0.0)

    return worst_val, mu_star


def max_inner_value_fast(indx, lam, fact, mu_guess=1.0):
    """
    Faster but potentially less robust version of max_inner_value.

    Uses bounded 1D optimization instead of solving the stationary-point
    polynomial exactly.
    """
    indx = np.asarray(indx, dtype=int).reshape(-1)
    lam = np.asarray(lam, dtype=float).reshape(-1)
    fact = np.asarray(fact, dtype=float).reshape(-1)

    def g(mu):
        pk = np.exp(-mu) * (mu ** indx) * fact[indx]
        return np.dot(lam, pk)

    res = minimize_scalar(
        lambda x: -g(x),
        bounds=(0.0, max(20.0, 3.0 * mu_guess)),
        method="bounded"
    )

    mu_star = float(res.x)
    val = float(g(mu_star))

    return max(val, 0.0), mu_star


def true_objective(probs, indx, fact, lam, imtol=1e-9):
    """
    Evaluate the final objective:
        obj = max(0, max_{mu >= 0} lam · p(mu)) - lam · probs
    """
    probs = np.asarray(probs, dtype=float).reshape(-1)
    lam = np.asarray(lam, dtype=float).reshape(-1)

    worst_val, mu_star = max_inner_value(indx, lam, fact, imtol=imtol)
    obj = worst_val - np.dot(lam, probs)
    return obj, worst_val, mu_star


def solve_semi_infinite_lp(probs, indx, fact, bounds,
                           mu_init=(0.0,),
                           tol=1e-10, max_iter=100, imtol=1e-9,lp_failed_continue=False):
    """
    Solve the semi-infinite LP by a cutting-plane / exchange method.

    At each iteration:
      1. solve the finite master LP for the current set of cuts mu_list
      2. compute the true worst-case value max(0, max_mu lam · p(mu))
      3. if the violation is small, stop
      4. otherwise add the new finite cut mu_star and repeat

    Because the master LP already contains the constraint t >= 0, the infinity
    branch is automatically included. Therefore no special case mu_star = None
    is needed.
    """
    probs = np.asarray(probs, dtype=float).reshape(-1)
    indx = np.asarray(indx, dtype=int).reshape(-1)
    fact = np.asarray(fact, dtype=float).reshape(-1)

    mu_list = [float(mu) for mu in mu_init]

    for it in range(max_iter):
        lam, t, lp_res = solve_master_lp(probs, indx, fact, bounds, mu_list,lp_failed_continue=lp_failed_continue)

        worst_val, mu_star = max_inner_value(indx, lam, fact, imtol=imtol)
        violation = worst_val - t

        if violation <= tol:
            obj, worst_val_chk, mu_star_chk = true_objective(
                probs, indx, fact, lam, imtol=imtol
            )
            return {
                "lam": lam,
                "t": t,
                "obj": obj,
                "num": -obj,
                "mu_star": mu_star_chk,
                "mu_list": mu_list,
                "iterations": it + 1,
                "success": True,
                "violation": violation,
                "lp_res": lp_res,
            }

        # Add new cut unless it is numerically redundant
        if not is_redundant_cut(mu_star, mu_list, indx, fact, row_tol=1e-12):
            mu_list.append(float(mu_star))
        else:
            obj, worst_val_chk, mu_star_chk = true_objective(
                probs, indx, fact, lam, imtol=imtol
                )
            return {
                "lam": lam,
                "t": t,
                "obj": obj,
                "num": -obj,
                "mu_star": mu_star_chk,
                "mu_list": mu_list,
                "iterations": it + 1,
                "success": False,
                "violation": violation,
                "lp_res": lp_res,
                "message": "Redundant cut encountered with positive violation."
                }

    obj, worst_val_chk, mu_star_chk = true_objective(
        probs, indx, fact, lam, imtol=imtol
    )
    return {
        "lam": lam,
        "t": t,
        "obj": obj,
        "num": -obj,
        "mu_star": mu_star_chk,
        "mu_list": mu_list,
        "iterations": max_iter,
        "success": False,
        "violation": violation,
        "lp_res": lp_res,
        "message": "Maximum number of cutting-plane iterations reached."
    }


