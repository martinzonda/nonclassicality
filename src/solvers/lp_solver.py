r"""Primary numerical nonclassicality solver: a semi-infinite linear program.

The witness optimisation solved here is

.. math::

    f(\boldsymbol\lambda)
        = \max\!\Big(0,\ \max_{\mu \ge 0} \boldsymbol\lambda\cdot\mathbf p(\mu)\Big)
          - \boldsymbol\lambda\cdot\mathbf P,

where :math:`p_k(\mu) = e^{-\mu}\,\mu^k/k!` are Poisson probabilities. The inner
maximisation over :math:`\mu` makes this a *semi-infinite* LP (infinitely many
constraints, one per :math:`\mu \ge 0`). It is solved by a cutting-plane /
exchange method: a finite master LP is solved, the most-violated :math:`\mu` is
found analytically from the stationary-point polynomial, the corresponding cut
is added, and the process repeats until the violation falls below tolerance.

A negative optimal objective certifies that ``probs`` is nonclassical.
"""

from __future__ import annotations

import logging
from typing import Sequence

import numpy as np
from numpy.typing import ArrayLike, NDArray
from scipy.optimize import linprog, minimize_scalar, OptimizeResult
from numpy.polynomial.polynomial import polyroots, polyval, polytrim

logger = logging.getLogger(__name__)

# Magnitude below which a Poisson row vector is treated as numerically zero,
# i.e. indistinguishable from the t >= 0 constraint already in the master LP.
# Intrinsic to the solver formulation, not a user-facing tolerance.
_ZERO_ROW_ATOL = 1e-14

Bounds = Sequence[tuple[float | None, float | None]]


def pvec_mu(mu: float, indx: ArrayLike, fact: ArrayLike) -> NDArray[np.float64]:
    r"""Poisson probability vector restricted to selected indices.

    Computes :math:`p_k(\mu) = e^{-\mu}\,\mu^k / k!` for the photon numbers
    ``k`` in ``indx``.

    Parameters
    ----------
    mu : float
        Poisson mean :math:`\mu \ge 0`.
    indx : array_like of int
        Selected photon-number indices ``k``.
    fact : array_like of float
        Inverse factorials with ``fact[k] = 1/k!`` for all ``k`` in ``indx``.

    Returns
    -------
    numpy.ndarray
        Vector ``p`` with ``p[j] = exp(-mu) * mu**indx[j] * fact[indx[j]]``.
    """
    indx = np.asarray(indx, dtype=int).reshape(-1)
    fact = np.asarray(fact, dtype=float).reshape(-1)
    mu = float(mu)

    return np.exp(-mu) * (mu ** indx) * fact[indx]


def is_redundant_cut(
    mu_star: float,
    mu_list: Sequence[float],
    indx: ArrayLike,
    fact: ArrayLike,
    row_tol: float = 1e-12,
) -> bool:
    """Test whether a candidate cut duplicates an existing one.

    A cut generated by ``mu_star`` is redundant if its Poisson row vector is
    numerically zero (already covered by ``t >= 0``) or matches the row vector
    of some ``mu`` already in ``mu_list``.

    Parameters
    ----------
    mu_star : float
        Candidate cut location.
    mu_list : sequence of float
        Cut locations already present in the master LP.
    indx : array_like of int
        Selected photon-number indices.
    fact : array_like of float
        Inverse factorials ``fact[k] = 1/k!``.
    row_tol : float, optional
        Relative tolerance for comparing row vectors. Default ``1e-12``.

    Returns
    -------
    bool
        ``True`` if the cut is numerically redundant, ``False`` otherwise.
    """
    p_new = pvec_mu(mu_star, indx, fact)

    # Numerically zero cut is already covered by t >= 0.
    if np.max(np.abs(p_new)) < _ZERO_ROW_ATOL:
        return True

    for mu_old in mu_list:
        p_old = pvec_mu(mu_old, indx, fact)

        # Compare the actual row vectors, not just the mu values.
        if np.max(np.abs(p_new - p_old)) <= row_tol * max(1.0, np.max(np.abs(p_new))):
            return True

    return False


def prune_duplicate_rows(
    A_ub: ArrayLike,
    b_ub: ArrayLike,
    row_tol: float = 1e-12,
) -> tuple[NDArray[np.float64], NDArray[np.float64]]:
    """Drop rows of ``A_ub`` that duplicate an earlier row.

    Since all ``b_ub`` entries are zero in this formulation, comparing the
    ``A_ub`` rows is sufficient. Improves conditioning for larger systems
    (``N_P > 12``).

    Parameters
    ----------
    A_ub : array_like, shape (m, n)
        Inequality constraint matrix.
    b_ub : array_like, shape (m,)
        Inequality right-hand side (all zeros here).
    row_tol : float, optional
        Relative tolerance for treating two rows as identical. Default
        ``1e-12``.

    Returns
    -------
    A_kept : numpy.ndarray
        Deduplicated constraint matrix.
    b_kept : numpy.ndarray
        Corresponding right-hand side.
    """
    A_ub = np.asarray(A_ub, dtype=float)
    b_ub = np.asarray(b_ub, dtype=float)

    keep_rows: list[NDArray[np.float64]] = []
    keep_rhs: list[float] = []

    for i in range(A_ub.shape[0]):
        row = A_ub[i]

        is_duplicate = False
        for kept in keep_rows:
            if np.max(np.abs(row - kept)) <= row_tol * max(1.0, np.max(np.abs(row))):
                is_duplicate = True
                break

        if not is_duplicate:
            keep_rows.append(row)
            keep_rhs.append(b_ub[i])

    return np.array(keep_rows, dtype=float), np.array(keep_rhs, dtype=float)


def solve_master_lp(
    probs: ArrayLike,
    indx: ArrayLike,
    fact: ArrayLike,
    bounds: Bounds,
    mu_list: Sequence[float],
    lp_failed_continue: bool = False,
) -> tuple[NDArray[np.float64], float, OptimizeResult]:
    r"""Solve the finite master LP for the current set of cuts.

    Solves

    .. math::

        \min_{\boldsymbol\lambda, t} \ t - \boldsymbol\lambda\cdot\mathbf P
        \quad\text{s.t.}\quad
        t \ge \boldsymbol\lambda\cdot\mathbf p(\mu_m)\ \forall \mu_m,\quad
        t \ge 0,

    with ``bounds`` on each component of :math:`\boldsymbol\lambda`. Tries the
    HiGHS dual simplex first, then the interior-point method as a fallback.

    Parameters
    ----------
    probs : array_like, shape (n,)
        Target probability vector :math:`\mathbf P`.
    indx : array_like of int, shape (n,)
        Selected photon-number indices.
    fact : array_like of float
        Inverse factorials ``fact[k] = 1/k!``.
    bounds : sequence of (float or None, float or None)
        Per-component bounds on :math:`\boldsymbol\lambda` (length ``n``).
    mu_list : sequence of float
        Current cut locations.
    lp_failed_continue : bool, optional
        If ``True``, return a safe fallback (``lam = 0``, ``t = 0``) instead of
        raising when the LP solver fails. Default ``False``.

    Returns
    -------
    lam : numpy.ndarray
        Optimal coefficient vector :math:`\boldsymbol\lambda`.
    t : float
        Optimal epigraph variable.
    res : scipy.optimize.OptimizeResult
        Raw solver result (or a synthesized fallback result).

    Raises
    ------
    ValueError
        If ``probs``, ``indx`` and ``bounds`` have inconsistent lengths.
    RuntimeError
        If both LP methods fail and ``lp_failed_continue`` is ``False``.
    """
    probs = np.asarray(probs, dtype=float).reshape(-1)
    indx = np.asarray(indx, dtype=int).reshape(-1)
    fact = np.asarray(fact, dtype=float).reshape(-1)

    n = len(probs)
    if len(indx) != n:
        raise ValueError(f"len(probs)={n} but len(indx)={len(indx)}")
    if len(bounds) != n:
        raise ValueError(f"len(bounds)={len(bounds)} but n={n}")

    # Objective: minimize t - lam . probs  ->  c = [-probs, 1].
    c = np.zeros(n + 1)
    c[:n] = -probs
    c[n] = 1.0

    A_ub: list[NDArray[np.float64]] = []
    b_ub: list[float] = []

    # Constraints: lam . p(mu_m) - t <= 0, one per cut.
    for mu in mu_list:
        p = pvec_mu(mu, indx, fact)
        # Skip cuts numerically indistinguishable from t >= 0.
        pmax = np.max(np.abs(p))
        if pmax < _ZERO_ROW_ATOL:
            continue

        # Scale each row for better conditioning of the constraint matrix.
        scale = max(1.0, pmax)

        row = np.zeros(n + 1)
        row[:n] = p / scale
        row[n] = -1.0 / scale
        A_ub.append(row)
        b_ub.append(0.0)

    # Constraint: t >= 0  <=>  -t <= 0.
    row = np.zeros(n + 1)
    row[n] = -1.0
    A_ub.append(row)
    b_ub.append(0.0)

    A_ub = np.array(A_ub, dtype=float)
    b_ub = np.array(b_ub, dtype=float)

    # Row pruning can improve stability for N_P > 12; disabled by default.
    # A_ub, b_ub = prune_duplicate_rows(A_ub, b_ub, row_tol=1e-12)

    lp_bounds = list(bounds) + [(None, None)]

    # First try the dual simplex, then fall back to interior-point.
    res = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=lp_bounds, method="highs-ds")
    if not res.success:
        res = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=lp_bounds, method="highs-ipm")

    # If still failed, either stop or return a safe fallback solution.
    if not res.success:
        if not lp_failed_continue:
            raise RuntimeError(f"linprog failed: {res.message}")

        logger.warning(
            "LP solver failed (%s); returning fallback lam=0, t=0.", res.message
        )
        lam = np.zeros(n, dtype=float)
        t = 0.0

        fallback_res = OptimizeResult({
            "x": np.concatenate([lam, [t]]),
            "success": False,
            "status": -999,
            "message": (
                "LP failed; returned fallback solution lam=0, t=0. "
                f"Original solver message: {res.message}"
            ),
            "fun": 0.0,
            "nit": 0,
            "lp_failed_fallback": True,
        })

        return lam, t, fallback_res

    lam = res.x[:n]
    t = res.x[n]
    return lam, t, res


def max_inner_value(
    indx: ArrayLike,
    lam: ArrayLike,
    fact: ArrayLike,
    imtol: float = 1e-9,
) -> tuple[float, float]:
    r"""Supremum of :math:`\boldsymbol\lambda\cdot\mathbf p(\mu)` over ``mu >= 0``.

    Finds the maximiser from the stationary-point polynomial
    :math:`\sum_k (\lambda_{k+1}-\lambda_k)\,\mu^k/k! = 0`, evaluating the
    objective at the positive real roots and the boundary ``mu = 0``.

    Parameters
    ----------
    indx : array_like of int
        Selected photon-number indices.
    lam : array_like of float
        Coefficient vector, aligned with ``indx``.
    fact : array_like of float
        Inverse factorials ``fact[k] = 1/k!``.
    imtol : float, optional
        Imaginary-part tolerance for accepting a polynomial root as real.
        Default ``1e-9``.

    Returns
    -------
    worst_val : float
        The supremum value clipped at 0, i.e.
        ``max(0, max_{mu>=0} lam . p(mu))``.
    mu_star : float
        Best finite candidate location (diagnostic only when ``worst_val``
        is the ``mu -> inf`` limit of 0).

    Raises
    ------
    ValueError
        If ``indx`` and ``lam`` have different lengths.

    Notes
    -----
    If every finite candidate is negative, the true supremum over ``mu >= 0``
    is 0, attained only as ``mu -> inf`` (since ``lam . p(mu) -> 0``). This is
    handled by clipping ``worst_val`` at 0; the outer LP covers that branch via
    the explicit ``t >= 0`` constraint.
    """
    indx = np.asarray(indx, dtype=int).reshape(-1)
    lam = np.asarray(lam, dtype=float).reshape(-1)
    fact = np.asarray(fact, dtype=float).reshape(-1)

    if indx.size == 0:
        return 0.0, 0.0

    if len(indx) != len(lam):
        raise ValueError(f"len(indx)={len(indx)} but len(lam)={len(lam)}")

    mxin = indx.max()

    # Dense lambda_k for k = 0, ..., mxin+1.
    lam_aux = np.zeros(mxin + 2, dtype=float)
    lam_aux[indx] = lam

    # Stationary-point polynomial: sum_k (lambda_{k+1} - lambda_k) mu^k / k! = 0.
    dcoef = (lam_aux[1:mxin + 2] - lam_aux[:mxin + 1]) * fact[:mxin + 1]
    dcoef = polytrim(dcoef)

    if dcoef.size <= 1:
        candidates = np.array([0.0])
    else:
        roots = polyroots(dcoef)
        mask = (np.abs(roots.imag) < imtol) & (roots.real > 0.0)
        candidates = np.concatenate(([0.0], roots.real[mask]))

    coef = lam_aux[:mxin + 1] * fact[:mxin + 1]
    vals = polyval(candidates, coef) * np.exp(-candidates)

    imax = np.argmax(vals)
    mu_star = float(candidates[imax])
    val = float(vals[imax])

    # Include the limiting value 0 from mu -> infinity.
    worst_val = max(val, 0.0)

    return worst_val, mu_star


def max_inner_value_fast(
    indx: ArrayLike,
    lam: ArrayLike,
    fact: ArrayLike,
    mu_guess: float = 1.0,
) -> tuple[float, float]:
    r"""Faster, less robust variant of :func:`max_inner_value`.

    Uses bounded 1D optimisation instead of solving the stationary-point
    polynomial exactly.

    Parameters
    ----------
    indx : array_like of int
        Selected photon-number indices.
    lam : array_like of float
        Coefficient vector, aligned with ``indx``.
    fact : array_like of float
        Inverse factorials ``fact[k] = 1/k!``.
    mu_guess : float, optional
        Scale hint; the search upper bound is ``max(20, 3 * mu_guess)``.
        Default ``1.0``.

    Returns
    -------
    worst_val : float
        ``max(0, max_{mu>=0} lam . p(mu))``.
    mu_star : float
        Maximiser found by the bounded search.
    """
    indx = np.asarray(indx, dtype=int).reshape(-1)
    lam = np.asarray(lam, dtype=float).reshape(-1)
    fact = np.asarray(fact, dtype=float).reshape(-1)

    def g(mu: float) -> float:
        pk = np.exp(-mu) * (mu ** indx) * fact[indx]
        return np.dot(lam, pk)

    res = minimize_scalar(
        lambda x: -g(x),
        bounds=(0.0, max(20.0, 3.0 * mu_guess)),
        method="bounded",
    )

    mu_star = float(res.x)
    val = float(g(mu_star))

    return max(val, 0.0), mu_star


def true_objective(
    probs: ArrayLike,
    indx: ArrayLike,
    fact: ArrayLike,
    lam: ArrayLike,
    imtol: float = 1e-9,
) -> tuple[float, float, float]:
    r"""Evaluate the witness objective for a fixed coefficient vector.

    Computes ``obj = max(0, max_{mu>=0} lam . p(mu)) - lam . probs``.

    Parameters
    ----------
    probs : array_like, shape (n,)
        Target probability vector.
    indx : array_like of int
        Selected photon-number indices.
    fact : array_like of float
        Inverse factorials ``fact[k] = 1/k!``.
    lam : array_like of float
        Coefficient vector.
    imtol : float, optional
        Imaginary-part tolerance forwarded to :func:`max_inner_value`.
        Default ``1e-9``.

    Returns
    -------
    obj : float
        The witness objective value (negative => nonclassical).
    worst_val : float
        ``max(0, max_{mu>=0} lam . p(mu))``.
    mu_star : float
        Maximiser location from :func:`max_inner_value`.
    """
    probs = np.asarray(probs, dtype=float).reshape(-1)
    lam = np.asarray(lam, dtype=float).reshape(-1)

    worst_val, mu_star = max_inner_value(indx, lam, fact, imtol=imtol)
    obj = worst_val - np.dot(lam, probs)
    return obj, worst_val, mu_star


def solve_semi_infinite_lp(
    probs: ArrayLike,
    indx: ArrayLike,
    fact: ArrayLike,
    bounds: Bounds,
    mu_init: Sequence[float] = (0.0,),
    tol: float = 1e-10,
    max_iter: int = 100,
    imtol: float = 1e-9,
    lp_failed_continue: bool = False,
) -> dict:
    r"""Solve the semi-infinite witness LP by a cutting-plane method.

    Each iteration: (1) solve the finite master LP for the current cuts,
    (2) compute the true worst-case value ``max(0, max_mu lam . p(mu))``,
    (3) stop if the violation is within ``tol``, otherwise (4) add the new cut
    ``mu_star`` and repeat. The master LP's ``t >= 0`` constraint already covers
    the ``mu -> inf`` branch, so no special ``mu_star = None`` case is needed.

    Parameters
    ----------
    probs : array_like, shape (n,)
        Target probability vector :math:`\mathbf P`.
    indx : array_like of int
        Selected photon-number indices.
    fact : array_like of float
        Inverse factorials ``fact[k] = 1/k!``.
    bounds : sequence of (float or None, float or None)
        Per-component bounds on :math:`\boldsymbol\lambda`.
    mu_init : sequence of float, optional
        Initial cut locations. Default ``(0.0,)``.
    tol : float, optional
        Violation tolerance for convergence. Default ``1e-10``.
    max_iter : int, optional
        Maximum cutting-plane iterations. Default ``100``.
    imtol : float, optional
        Imaginary-part tolerance forwarded to :func:`max_inner_value`.
        Default ``1e-9``.
    lp_failed_continue : bool, optional
        Forwarded to :func:`solve_master_lp`. Default ``False``.

    Returns
    -------
    dict
        Result with keys ``lam``, ``t``, ``obj``, ``num`` (``= -obj``),
        ``mu_star``, ``mu_list``, ``iterations``, ``success``, ``violation``,
        ``lp_res`` and (when not converged) ``message``.

    Raises
    ------
    RuntimeError
        If the master LP fails and ``lp_failed_continue`` is ``False``.
    """
    probs = np.asarray(probs, dtype=float).reshape(-1)
    indx = np.asarray(indx, dtype=int).reshape(-1)
    fact = np.asarray(fact, dtype=float).reshape(-1)

    mu_list = [float(mu) for mu in mu_init]

    for it in range(max_iter):
        lam, t, lp_res = solve_master_lp(
            probs, indx, fact, bounds, mu_list, lp_failed_continue=lp_failed_continue
        )

        worst_val, mu_star = max_inner_value(indx, lam, fact, imtol=imtol)
        violation = worst_val - t

        if violation <= tol:
            obj, worst_val_chk, mu_star_chk = true_objective(
                probs, indx, fact, lam, imtol=imtol
            )
            return {
                "lam": lam,
                "t": t,
                "obj": obj,
                "num": -obj,
                "mu_star": mu_star_chk,
                "mu_list": mu_list,
                "iterations": it + 1,
                "success": True,
                "violation": violation,
                "lp_res": lp_res,
            }

        # Add the new cut unless it is numerically redundant.
        if not is_redundant_cut(mu_star, mu_list, indx, fact, row_tol=1e-12):
            mu_list.append(float(mu_star))
        else:
            obj, worst_val_chk, mu_star_chk = true_objective(
                probs, indx, fact, lam, imtol=imtol
            )
            return {
                "lam": lam,
                "t": t,
                "obj": obj,
                "num": -obj,
                "mu_star": mu_star_chk,
                "mu_list": mu_list,
                "iterations": it + 1,
                "success": False,
                "violation": violation,
                "lp_res": lp_res,
                "message": "Redundant cut encountered with positive violation.",
            }

    obj, worst_val_chk, mu_star_chk = true_objective(
        probs, indx, fact, lam, imtol=imtol
    )
    return {
        "lam": lam,
        "t": t,
        "obj": obj,
        "num": -obj,
        "mu_star": mu_star_chk,
        "mu_list": mu_list,
        "iterations": max_iter,
        "success": False,
        "violation": violation,
        "lp_res": lp_res,
        "message": "Maximum number of cutting-plane iterations reached.",
    }
